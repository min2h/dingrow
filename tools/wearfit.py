#!/usr/bin/env python3
"""Measures every pet sprite (silhouette rows, eyes, face bottom) so worn outfits can be fitted
to the actual body. Writes composeApp/.../ui/WearFit.kt. Re-run when pet art changes."""
import glob, os, re
import numpy as np
from PIL import Image
D = 'composeApp/src/commonMain/composeResources/drawable'
poses = re.compile(r'^(.*?)(?:_(blink|eat|happy|sleep|walk_left))?$')
species = set(re.findall(r'"(\w+)_blink"', open('composeApp/src/commonMain/kotlin/app/mongle/ui/SpeciesPoses.kt').read()))
ids = ['egg'] + ['base_' + p for p in ['idle', 'blink', 'eat', 'happy', 'sleep', 'walk_left']]
for s in sorted(species):
    ids += [s] + [f'{s}_{p}' for p in ['blink', 'eat', 'happy', 'sleep', 'walk_left'] if os.path.exists(f'{D}/{s}_{p}.webp')]
ROWS = 24
out = {}
for i in ids:
    im = np.asarray(Image.open(f'{D}/{i}.webp').convert('RGBA').resize((256, 256), Image.LANCZOS)).astype(float)
    a = im[..., 3] > 140
    ys, xs = np.nonzero(a)
    top, bot = ys.min() / 256, (ys.max() + 1) / 256
    mid = a[:, 103:153].any(axis=1); headTop = np.argmax(mid) / 256
    L, R = [], []
    for k in range(ROWS):
        y = int((k + .5) / ROWS * 256); row = np.nonzero(a[y])[0]
        L.append(row.min() / 256 if len(row) else .5); R.append((row.max() + 1) / 256 if len(row) else .5)
    lum = im[..., :3].max(axis=2)
    h = bot - top
    dark = a & (lum < 95)
    dark[: int((top + .15 * h) * 256)] = False; dark[int((top + .78 * h) * 256):] = False
    dy, dx = np.nonzero(dark)
    cx = (xs.min() + xs.max()) / 2
    ok = 20 < len(dy) < 1500
    if ok:
        l = dx < cx; r = ~l
        ok = l.sum() > 4 and r.sum() > 4
    if ok:
        eL = (dx[l].mean() / 256, dy[l].mean() / 256); eR = (dx[r].mean() / 256, dy[r].mean() / 256)
        eyeY = (eL[1] + eR[1]) / 2
        band = (dx > dx[l].mean()) & (dx < dx[r].mean())
        fb = (dy[band].max() / 256 if band.any() else eyeY + .06)
        faceBot = min(max(fb, eyeY + .05), eyeY + .16) + .035
        est = False
    else:
        eyeY = top + .42 * h; eL = (.38, eyeY); eR = (.62, eyeY); faceBot = eyeY + .12; est = True
    out[i] = (top, headTop, bot, eL[0], eR[0], eyeY, faceBot, L, R, est)
q = lambda v: str(int(round(v * 1000)))
lines = ['// GENERATED by tools/wearfit.py from the pet sprites. Do not edit by hand.', 'package app.mongle.ui', '',
 '/** Measured body geometry of one pet sprite, in fractions of its square box. */',
 'class SpriteFit(val top: Float, val headTop: Float, val bottom: Float, val eyeLX: Float, val eyeRX: Float, val eyeY: Float, val faceBottom: Float, val left: FloatArray, val right: FloatArray) {',
 '    private fun at(a: FloatArray, y: Float): Float { val p = (y * a.size - 0.5f).coerceIn(0f, a.size - 1f); val i = p.toInt().coerceAtMost(a.size - 2); val t = p - i; return a[i] * (1 - t) + a[i + 1] * t }',
 '    fun leftAt(y: Float) = at(left, y)', '    fun rightAt(y: Float) = at(right, y)', '    fun widthAt(y: Float) = rightAt(y) - leftAt(y)',
 '    val cx get() = (eyeLX + eyeRX) / 2', '}', '',
 '/** id, then top headTop bottom eyeLX eyeRX eyeY faceBottom, then %d left and %d right edges (all x1000). */' % (ROWS, ROWS),
 'object WearFit {',
 '    fun of(assetId: String): SpriteFit = table[assetId] ?: table[assetId.substringBefore("_")] ?: table.getValue("base_idle")',
 '    fun has(assetId: String) = assetId in table', '    val ids: Set<String> get() = table.keys',
 '    private val table: Map<String, SpriteFit> by lazy {',
 '        raw.associate { line -> val p = line.split(" "); val v = p.drop(1).map { it.toInt() / 1000f }',
 '            p[0] to SpriteFit(v[0], v[1], v[2], v[3], v[4], v[5], v[6], v.subList(7, 7 + %d).toFloatArray(), v.subList(7 + %d, 7 + %d).toFloatArray()) }' % (ROWS, ROWS, 2 * ROWS),
 '    }', '    private val raw = arrayOf(']
for i, (t, ht, b, ex1, ex2, ey, fbt, L, R, est) in out.items():
    lines.append('        "' + ' '.join([i] + [q(v) for v in (t, ht, b, ex1, ex2, ey, fbt, *L, *R)]) + '",' + (' // eyes estimated' if est else ''))
lines += ['    )', '}', '']
open('composeApp/src/commonMain/kotlin/app/mongle/ui/WearFit.kt', 'w').write('\n'.join(lines))
print(len(out), 'estimated:', [k for k, v in out.items() if v[-1]])
